# ── Normalisierung ──────────────────────────────────────────────────────────
def _norm(s: str) -> str:
    """Kleinbuchstaben, Umlaute normalisieren, Sonderzeichen entfernen."""
    s = s.lower().strip()
    replacements = {
        'ä':'ae','ö':'oe','ü':'ue','ß':'ss',
        'é':'e','è':'e','ê':'e','ë':'e',
        'à':'a','â':'a','á':'a',
        'ñ':'n','ç':'c','ô':'o','î':'i','û':'u',
    }
    for ch, rep in replacements.items():
        s = s.replace(ch, rep)
    s = re.sub(r"[&'\"]", '', s)
    return s

